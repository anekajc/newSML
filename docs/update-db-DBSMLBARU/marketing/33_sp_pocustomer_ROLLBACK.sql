ALTER procedure [dbo].[Sp_POCustomer]
--declare
@CHOICE CHAR,
@TglTerima DaTETIME,
@POCUSTOMER VARCHAR(100),
@KODECUSTSUPP VARCHAR(30),
@ID INT,
@RpPO Numeric(18,2)=0


AS
Begin tran

IF @CHOICE='I'
BEGIN
INSERT INTO DBPOCUSTSUPP (TGLINPUT,TGLTERIMA,POCUSTOMER,KODECUSTSUPP,RpPO)
VALUES (GETDATE(),@TglTerima,@POCUSTOMER,@KODECUSTSUPP,@RpPO)
END


IF @CHOICE='U'
BEGIN
UPDATE DBPOCUSTSUPP SET TGLTERIMA=@TglTerima,POCUSTOMER=@POCUSTOMER,KODECUSTSUPP=@KODECUSTSUPP,RpPO=@RpPO WHERE ID=@ID
END


IF @CHOICE='D'
BEGIN
DELETE DBPOCUSTSUPP WHERE ID=@ID
END

if @@error<>0  goto jikasalah
Commit tran
Return
JikaSalah: Rollback tran
           Return
GO
